def plot_metrics_by_condition(data, lip, out_png):
    """Two panels (IS, WER): per-video lines over the 4 ordered arms + black arm-mean w/ 95% CI."""
    xlabels = ["4K\n(baseline)", "4K ctrl\n(re-encode)", "2K\n(x2/3)", "1080p\n(x0.5)"]
    x = np.arange(4)
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.6), dpi=160)
    fig.patch.set_facecolor(SURFACE)
    for ax, key, title, ylab in [
            (axes[0], "is", "Intelligibility Score by input resolution", "mean IS (0–5)"),
            (axes[1], "wer", "WER by input resolution", "mean WER % (uncapped)")]:
        ax.set_facecolor(SURFACE)
        ends = []
        for stem in STEMS:
            ys = [data["per_video"][a][stem][key + "_mean"] for a in ARM_ORDER]
            ax.plot(x, ys, color=VIDEO_COLORS[stem], lw=1.6, marker="o", ms=4.5,
                    alpha=0.9, zorder=2)
            ends.append((stem, ys[-1]))
        # direct end labels with simple collision stagger (min gap = 4% of y-span)
        yspan = (max(e[1] for e in ends) - min(e[1] for e in ends)) or 1.0
        min_gap = 0.055 * max(yspan, 1e-9)
        placed = []
        for stem, y0 in sorted(ends, key=lambda e: e[1]):
            y = y0
            if placed and y - placed[-1] < min_gap:
                y = placed[-1] + min_gap
            placed.append(y)
            ax.annotate(stem.replace("img_", ""), (x[-1], y), xytext=(7, 0),
                        textcoords="offset points", fontsize=8,
                        color=VIDEO_COLORS[stem], va="center")
        means = [data["arms_mbr"][a][key + "_mean"] for a in ARM_ORDER]
        los = [data["arms_mbr"][a][key + "_ci"][0] for a in ARM_ORDER]
        his = [data["arms_mbr"][a][key + "_ci"][1] for a in ARM_ORDER]
        ax.errorbar(x, means, yerr=[np.array(means) - np.array(los),
                                    np.array(his) - np.array(means)],
                    color=INK, lw=2.4, marker="o", ms=6, capsize=3, zorder=3)
        ax.set_xticks(x)
        ax.set_xticklabels(xlabels, fontsize=8.5, color=INK2)
        ax.set_title(title, fontsize=11, color=INK, pad=10)
        ax.set_ylabel(ylab, fontsize=9, color=INK2)
        ax.grid(axis="y", color=GRID, lw=0.7)
        ax.tick_params(colors=MUTED, labelsize=8.5)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            ax.spines[s].set_color(BASELINE_AX)
        ax.set_xlim(-0.25, 3.65)
    handles = [plt.Line2D([], [], color=VIDEO_COLORS[s], lw=1.6, marker="o", ms=4.5,
                          label=s) for s in STEMS]
    handles.append(plt.Line2D([], [], color=INK, lw=2.4, marker="o", ms=6,
                              label="mean over scored segments ± 95% CI"))
    fig.legend(handles=handles, loc="lower center", ncol=6, fontsize=8, frameon=False,
               bbox_to_anchor=(0.5, -0.03))
    fig.suptitle("Egla-Kafe resolution ablation — same 175 segments, hyp_mbr text "
                 "(5 iPhone videos; turn boundaries held fixed)",
                 fontsize=9.5, color=INK2, y=1.005)
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(out_png, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)


