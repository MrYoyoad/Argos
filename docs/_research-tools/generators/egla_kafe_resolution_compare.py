def toks(s):
    return TOKEN_RE.findall((s or "").strip().lower())


def fnum(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def ci95(vals):
    vals = [v for v in vals if v is not None and not (isinstance(v, float) and math.isnan(v))]
    if not vals:
        return (None, None, None, 0)
    a = np.array(vals, dtype=float)
    m = float(a.mean())
    if len(a) < 2:
        return (m, m, m, len(a))
    se = a.std(ddof=1) / math.sqrt(len(a))
    t = sps.t.ppf(0.975, len(a) - 1)
    return (m, m - t * se, m + t * se, len(a))


def ensure_mbr_report(arm):
    c = ARMS[arm]
    if os.path.exists(c["report_mbr"]):
        return
    out_dir = os.path.dirname(c["report_mbr"])
    print(f"[regen] {arm}: building MBR-displayed report -> {out_dir}", file=sys.stderr)
    subprocess.run([sys.executable, MAKE_REPORT, "--jsonl", c["hypo_corrected"],
                    "--out_dir", out_dir, "--compute-is",
                    "--aggregated", c["aggregated"], "--display-method", "hyp_mbr"],
                   check=True)


def load_report(path):
    """report.csv -> {utt_id: row-dict with parsed metrics} (img_* rows only)."""
    out = {}
    with open(path, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            u = r["utt_id"]
            if not u.startswith("img_"):
                continue
            out[u] = {"ref": r["ref"], "hyp": r["hyp"],
                      "wer": fnum(r["wer_%"]), "wwer": fnum(r["wwer_%"]),
                      "nea_f1": fnum(r["nea_f1_%"]), "is": fnum(r["is_score"])}
    return out


def load_word_probs(arm):
    """Per-segment mean raw word prob from aggregated.json: hyp_mbr.word_confs + hyp_top1_word_confs."""
    agg = json.load(open(ARMS[arm]["aggregated"], encoding="utf-8"))
    mbr, top1 = {}, {}
    for u, v in agg.items():
        if not u.startswith("img_"):
            continue
        wc = (v.get("hyp_mbr") or {}).get("word_confs") or []
        ps = [p for _, p in wc if isinstance(p, (int, float))]
        mbr[u] = float(np.mean(ps)) if ps else None
        wt = v.get("hyp_top1_word_confs") or []
        pt = [p for _, p in wt if isinstance(p, (int, float))]
        top1[u] = float(np.mean(pt)) if pt else None
    return mbr, top1


def load_align_conf(arm):
    prov = json.load(open(ARMS[arm]["provenance"], encoding="utf-8"))
    return {u: p.get("align_conf") for u, p in prov.items() if u.startswith("img_")}


def parse_lip_px():
    """lip_pixel_measurements.txt -> {arm: {stem: {frame,face,mouth}}} (medians, FaceMesh)."""
    sec_to_arm = {c["lip_section"]: a for a, c in ARMS.items()}
    out = {a: {} for a in ARMS}
    cur = None
    row_re = re.compile(r"^\s+(img_\d+): frame (\d+)x\d+, face~(\d+)px, MOUTH~(\d+)px")
    for line in open(LIP_TXT, encoding="utf-8"):
        m = re.match(r"^== (.+) ==\s*$", line)
        if m:
            cur = sec_to_arm.get(m.group(1))
            continue
        m = row_re.match(line)
        if m and cur:
            out[cur][m.group(1)] = {"frame": int(m.group(2)), "face": int(m.group(3)),
                                    "mouth": int(m.group(4))}
    for a in ARMS:
        assert set(out[a]) == set(STEMS), f"lip px parse incomplete for {a}: {sorted(out[a])}"
    return out


def wer_fixed_ref(ref_text, hyp_text):
    """Uncapped word-level WER (%) with the aligner's tokenization; None if ref empty."""
    import editdistance
    r, h = toks(ref_text), toks(hyp_text)
    if not r:
        return None
    return 100.0 * editdistance.eval(r, h) / len(r)


def arm_summary(rows, word_probs, align_conf):
    """Means over scored rows (ref non-empty -> metric present), matching the June reporting
    basis. n_total=175 everywhere; n_scored varies per arm because the decode-anchored aligner
    matches fewer turns when the decode degrades (itself an outcome, reported)."""
    iss = [r["is"] for r in rows.values() if r["is"] is not None]
    wers = [r["wer"] for r in rows.values() if r["wer"] is not None]
    m_is, lo_is, hi_is, n_sc = ci95(iss)
    m_wer, lo_wer, hi_wer, _ = ci95(wers)
    n = len(rows)
    nonempty = [u for u, r in rows.items() if r["hyp"].strip()]
    return {
        "n_total": n, "n_scored": n_sc,
        "is_mean": m_is, "is_ci": [lo_is, hi_is],
        "wer_mean": m_wer, "wer_ci": [lo_wer, hi_wer],
        "wwer_mean": ci95([r["wwer"] for r in rows.values()])[0],
        "nea_f1_mean": ci95([r["nea_f1"] for r in rows.values()])[0],
        "useful_pct": 100.0 * sum(1 for v in iss if v >= 2.0) / n_sc,
        "clear_pct": 100.0 * sum(1 for v in iss if v >= 3.0) / n_sc,
        "niv_y_pct": 100.0 * sum(1 for v in iss if v >= 3.80) / n_sc,
        "halluc_pct": 100.0 * sum(1 for v in wers if v >= 100.0) / len(wers),
        "empty_pct": 100.0 * (n - len(nonempty)) / n,
        "mean_word_prob": ci95([word_probs.get(u) for u in rows])[0],
        "mean_align_conf": ci95([align_conf.get(u) for u in rows])[0],
    }


def paired_tests(rows_a, rows_b, key):
    """Wilcoxon signed-rank on per-segment metric `key` for arms a->b (delta = b - a).
    Pairs where either arm lacks the metric (empty aligned ref) are dropped."""
    common = sorted(u for u in set(rows_a) & set(rows_b)
                    if rows_a[u][key] is not None and rows_b[u][key] is not None)
    a = np.array([rows_a[u][key] for u in common], dtype=float)
    b = np.array([rows_b[u][key] for u in common], dtype=float)
    d = b - a
    nz = int(np.sum(d != 0))
    res = {"n": len(common), "n_changed": nz,
           "mean_delta": float(d.mean()), "median_delta": float(np.median(d))}
    if nz == 0:
        res.update({"W": None, "p": None})
        return res
    try:
        W, p = sps.wilcoxon(a, b, zero_method="wilcox", alternative="two-sided")
        res.update({"W": float(W), "p": float(p)})
    except ValueError as e:
        res.update({"W": None, "p": None, "err": str(e)})
    return res


def text_changed(rows_a, rows_b):
    common = sorted(set(rows_a) & set(rows_b))
    ch = sum(1 for u in common if rows_a[u]["hyp"].strip() != rows_b[u]["hyp"].strip())
    return 100.0 * ch / len(common)


def ref_changed(rows_a, rows_b):
    common = sorted(set(rows_a) & set(rows_b))
    ch = sum(1 for u in common if rows_a[u]["ref"].strip() != rows_b[u]["ref"].strip())
    return 100.0 * ch / len(common)


def fmt_p(p):
    if p is None:
        return "n/a"
    return f"{p:.4f}" if p >= 1e-4 else f"{p:.1e}"


